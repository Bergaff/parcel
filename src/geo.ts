function pairKey(a: string, b: string): string {
  const [x, y] = [a.trim().toLowerCase(), b.trim().toLowerCase()].sort();
  return `${x}|${y}`;
}

/** Расстояние по прямой (км) — для оценки, когда точного дорожного нет. */
export function straightKm(a: CityGeo, b: CityGeo): number {
  const toRad = (d: number) => (d * Math.PI) / 180;
  const dLat = toRad(b.lat - a.lat);
  const dLon = toRad(b.lon - a.lon);
  const lat = toRad((a.lat + b.lat) / 2);
  // малые расстояния считаем в плоской проекции — точности до километра хватает
  const x = dLon * 6371 * Math.cos(lat);
  const y = dLat * 6371;
  return Math.sqrt(x * x + y * y);
}

/**
 * Сколько километров по дороге между городами. Точное значение из таблицы,
 * иначе оценка по прямой × 1,25 с округлением до 10 км; null — города не знаем.
 */
export function routeKm(from: string, to: string): number | null {
  if (from.trim().toLowerCase() === to.trim().toLowerCase()) return 0;
  const known = ROAD_KM[pairKey(from, to)];
  if (known) return known;
  const a = CITY_GEO[from];
  const b = CITY_GEO[to];
  if (!a || !b) return null;
  return Math.max(10, Math.round((straightKm(a, b) * 1.25) / 10) * 10);
}

/** Сколько часов за рулём: средняя 80 км/ч + полчаса, округление до 0,5. */
export function driveHours(km: number): number {
  if (km <= 0) return 0;
  return Math.max(0.5, Math.round((km / 80 + 0.5) * 2) / 2);
}

/** «9,5» → «9,5», «10» → «10»: русская дробная часть в тексте. */
export function fmtHours(h: number): string {
  return String(h).replace('.', ',');
}

/** Пункты пропуска между странами двух городов (пусто, если их нет/Шенген). */
export function crossingsFor(from: string, to: string): Array<[string, string]> {
  const a = CITY_GEO[from]?.c;
  const b = CITY_GEO[to]?.c;
  if (!a || !b || a === b) return [];
  // коды стран — заглавные, поэтому ключ собираем отдельно от pairKey (тот
  // приводит к нижнему регистру: города)
  const key = [a, b].sort().join('|');
  const list = CROSSINGS[key as keyof typeof CROSSINGS];
  return list ? [...list] : [];
}

export interface TripInfo {
  km: number;
  hours: number;
  hoursText: string;
  /** «Беларусь — Польша» — только когда граница действительно есть. */
  border: string | null;
  crossings: Array<[string, string]>;
}

/** Всё, что страница маршрута говорит о дороге. null — города неизвестны. */
export function tripInfo(from: string, to: string): TripInfo | null {
  const km = routeKm(from, to);
  if (km == null || km <= 0) return null;
  const a = CITY_GEO[from]?.c ?? null;
  const b = CITY_GEO[to]?.c ?? null;
  const crossBorder = Boolean(a && b && a !== b);
  // внутри Шенгена контроля на дорогах нет — не пугаем границей
  const schengenInside = Boolean(a && b && SCHENGEN.has(a) && SCHENGEN.has(b));
  const hours = driveHours(km);
  return {
    km,
    hours,
    hoursText: fmtHours(hours),
    border: crossBorder && !schengenInside
      ? `${COUNTRY_NAME[a!] ?? a} — ${COUNTRY_NAME[b!] ?? b}`
      : null,
    crossings: crossBorder && !schengenInside ? crossingsFor(from, to) : [],
  };
}
