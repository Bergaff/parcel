/**
 * Ключ словаря: строчными, «ё» → «е», пробелы в один.
 *
 * Специально БЕЗ normalizeCity: тот гоняет регулярки по словарю форм городов,
 * и 2900 вызовов на старте модуля съели бы заметную часть CPU-лимита воркера
 * (инициализация модуля в него входит). normalizeCity зовётся один раз — на
 * запрос, в forumCountryOfCity. На совпадение это не влияет: названия здесь
 * стоят в именительном падеже, а в базу город попадает уже нормализованным,
 * разница между «Гродзиск-Мазовецкий» и «Гродзиск-мазовецкий» исчезает
 * в нижнем регистре.
 */
function fold(city: string): string {
  return city.toLowerCase().replace(/ё/g, 'е').replace(/\s+/g, ' ').trim();
}

/** Индекс город → страна. Приоритет: EXTRA (осознанные решения по спорным
 *  городам), затем пункты пропуска из CROSSINGS, затем CITY_GEO. */
const INDEX = new Map<string, string>();

function put(city: string, country: string): void {
  const key = fold(city);
  if (key) INDEX.set(key, country);
}

for (const [name, geo] of Object.entries(CITY_GEO)) {
  const country = COUNTRY_NAME[geo.c];
  if (country) put(name, country);
}

// «Гродно → Кузница»: люди пишут пункт пропуска вместо города на той стороне
for (const [key, pairs] of Object.entries(CROSSINGS)) {
  const [a, b] = key.split('|');
  if (!a || !b) continue;
  const nameA = COUNTRY_NAME[a];
  const nameB = COUNTRY_NAME[b];
  for (const [cityA, cityB] of pairs) {
    if (nameA) put(cityA, nameA);
    if (nameB) put(cityB, nameB);
  }
}

for (const [country, cities] of Object.entries(EXTRA)) {
  for (const city of cities) put(city, country);
}

/**
 * Страна города для раскладки по комнатам: «Пинск» → «беларусь».
 * Возвращает строчное имя страны (как в CITY_COUNTRY.name) или null, если
 * города не знаем: тогда заявка уходит в «прочее», как и раньше.
 */
export function forumCountryOfCity(city: string): string | null {
  // сначала как написано, затем через normalizeCity: «из Пинска» → «Пинск»
  const country = INDEX.get(fold(city)) ?? INDEX.get(fold(normalizeCity(city)));
  return country ? country.toLowerCase() : null;
}

/** Все страны, которые знает словарь комнат. Нужны, чтобы `/здесь Россия ↔
 *  Турция` разбиралось как правило «страна ↔ страна»: список стран в боте
 *  раньше строился из словаря витрины, где Турции, Китая и Сербии нет. */
export const FORUM_COUNTRIES: string[] = [...new Set(INDEX.values())];

/** Сколько городов знает словарь — для диагностики (/форум) и логов. */
export function forumCityCount(): number {
  return INDEX.size;
}
