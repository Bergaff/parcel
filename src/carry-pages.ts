/** Страница категории по слагу; null — адреса нет (честный 404). */
export function resolveCarryPage(slug: string): CarryPage | null {
  const clean = decodeURIComponent(slug || '').toLowerCase().trim();
  return CARRY_PAGES.find((p) => p.slug === clean) ?? null;
}

/** Все адреса раздела — для sitemap-pages.xml. */
export function carryPaths(): string[] {
  return ['/peredat', ...CARRY_PAGES.map((p) => `/peredat/${p.slug}`)];
}

/** Категории для подвала SEO-страниц: самые частые темы передач. */
const FOOT_CARRY_SLUGS = ['dokumenty', 'lekarstva', 'posylki', 'produkty', 'tekhnika', 'veshchi'];
export const FOOT_CARRY: Array<{ slug: string; label: string }> = FOOT_CARRY_SLUGS
  .map((s) => resolveCarryPage(s))
  .filter((p): p is CarryPage => p !== null)
  .map((p) => ({ slug: p.slug, label: p.og }));
