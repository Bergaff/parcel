-- Поиск по городам и тексту без учёта регистра: колонки from_city_lc,
-- to_city_lc и description_lc в таблице listings.
--
-- Зачем. Раньше города сравнивались GLOB-шаблоном «*[Аа][Мм][Сс]…» — класс на
-- каждую букву. SQLite отвергает такие шаблоны целиком («LIKE or GLOB pattern
-- too complex», лимит 10 спецэлементов), поэтому доска отдавала 500 на любом
-- городе от девяти букв (Амстердам, Санкт-Петербург, Ивано-Франковск) и на
-- любом поисковом запросе от девяти символов («лекарства», «документы»).
-- Встроенный lower() в SQLite знает только ASCII, поэтому нижний регистр
-- храним рядом с текстом: колонки заполняет JS при записи объявления, а
-- старые строки — одноразовый UPDATE цепочкой REPLACE.
--
-- Почему здесь нет ALTER TABLE. Колонки добавляет сам воркер
-- (ensureSearchColumns в src/store.ts): он проверяет PRAGMA table_info и
-- добавляет только недостающее, поэтому работает и на свежей базе, и на базе,
-- где миграцию ещё не применяли. ALTER TABLE в этом файле на такой базе упал
-- бы с «duplicate column name» и заблокировал все последующие миграции.
-- Индексы и заполнение воркер тоже делает сам (CREATE INDEX IF NOT EXISTS +
-- UPDATE ... WHERE *_lc IS NULL).
--
-- Файл оставлен как запись в истории схемы: выполнять здесь нечего.
